# Serials already in the wild come from a text box, so they do not carry a
# model. This maps what can be read off a Hitachi serial: the leading figures
# are the machine size, and the Zaxis-7 range is what this catalogue holds
# fitment for.
SERIAL_PREFIX_TO_MODEL = {
    "ZX210": "ZX210-7",
    "ZX250": "ZX250LC-7",
    "ZX350": "ZX350LC-7",
    "ZX490": "ZX490LCH-7",
}

# What a serial gets when nothing can be read off it at all.
#
# There is one such serial in the existing data — "AXZ120" — and it is the
# reason this migration exists: it is not a Hitachi model, it fits nothing,
# and it was accepted because the column was free text. It cannot be dropped
# without deleting somebody's requirement, and it cannot be left without a
# model because fitment is now validated against one. So it is assigned the
# model that keeps its existing requirement valid, and it is flagged here
# rather than quietly fixed.
FALLBACK_MODEL = "ZX350LC-7"


def _model_for(serial: str) -> str:
    upper = serial.upper()
    for prefix, model in SERIAL_PREFIX_TO_MODEL.items():
        if upper.startswith(prefix):
            return model
    return FALLBACK_MODEL


