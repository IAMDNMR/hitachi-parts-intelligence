def _backfill() -> None:
    """Give every existing requirement a real machine.

    Everything created here is marked as migrated so it is obvious later which
    records were reconstructed from a text field and which were entered
    properly. Nothing is deleted and no requirement is dropped.
    """
    conn = op.get_bind()

    serials = [
        row[0]
        for row in conn.execute(
            sa.text("SELECT DISTINCT machine_serial FROM requirements")
        )
    ]
    if not serials:
        return

    # One owner and one supporter for everything reconstructed. Inventing a
    # plausible customer per machine would be inventing history; one clearly
    # labelled placeholder is honest and can be corrected by hand.
    conn.execute(
        sa.text(
            "INSERT INTO customers (id, name, region) VALUES "
            "('migrated', 'Unassigned (migrated)', 'Unknown')"
        )
    )
    conn.execute(
        sa.text(
            "INSERT INTO dealers (id, name, region) VALUES "
            "('migrated', 'Unassigned (migrated)', 'Unknown')"
        )
    )

    for serial in serials:
        machine_id = serial.lower().replace(" ", "-")
        conn.execute(
            sa.text(
                "INSERT INTO machines "
                "(id, serial_number, model, customer_id, dealer_id, "
                " commissioned_at, status, warranty_end) "
                # 'WORKING', not 'working'. SQLAlchemy's non-native Enum
                # persists the member NAME, which is what the ORM reads back
                # and what the existing `stage` column already contains.
                # Writing the value here produced rows the application could
                # not load at all.
                "VALUES (:id, :serial, :model, 'migrated', 'migrated', "
                " :commissioned, 'WORKING', NULL)"
            ),
            {
                "id": machine_id,
                "serial": serial,
                "model": _model_for(serial),
                # Unknown, and said so by being the epoch rather than a
                # plausible date somebody might later mistake for a fact.
                "commissioned": "1970-01-01 00:00:00",
            },
        )
        conn.execute(
            sa.text(
                "UPDATE requirements SET machine_id = :id WHERE machine_serial = :serial"
            ),
            {"id": machine_id, "serial": serial},
        )


